// Sơ đồ chỗ ngồi mặc định
export function generateInitialSeats(students: Student[]): SeatSlot[] {
  const seats: SeatSlot[] = [];
  // 4 tổ (columns 1..4), mỗi tổ có 5 bàn (rows 1..5), mỗi bàn 2 ghế (left, right)
  let studentIdx = 0;
  for (let col = 1; col <= 4; col++) {
    for (let row = 1; row <= 5; row++) {
      const deskNum = (col - 1) * 5 + row;
      // Trái
      const studentLeft = studentIdx < students.length ? students[studentIdx].id : null;
      seats.push({
        id: `seat-${col}-${row}-L`,
        column: col,
        row,
        table: deskNum,
        seatPosition: 'left',
        studentId: studentLeft,
      });
      studentIdx++;

      // Phải (nếu bàn thứ 5 của tổ không đủ học sinh thì để trống)
      const studentRight = studentIdx < students.length ? students[studentIdx].id : null;
      seats.push({
        id: `seat-${col}-${row}-R`,
        column: col,
        row,
        table: deskNum,
        seatPosition: 'right',
        studentId: studentRight,
      });
      studentIdx++;
    }
  }
  return seats;
}

