// Helper sinh điểm số mẫu chân thực cho 36 học sinh
export function generateMockScores(students: Student[], subjects: Subject[]): Record<string, StudentTermScores> {
  const result: Record<string, StudentTermScores> = {};

  students.forEach((student, index) => {
    const scores: Record<string, any> = {};

    // Điểm nền dựa trên học lực
    const isTopStudent = index === 0 || index === 1 || index === 2 || index === 4 || index === 35;
    const isGoodStudent = !isTopStudent && (index % 3 !== 0);
    const isAverage = !isTopStudent && !isGoodStudent;

    subjects.forEach((sub) => {
      let base = 7.5;
      if (isTopStudent) base = 8.8;
      else if (isGoodStudent) base = 7.8;
      else base = 6.2;

      // Môn sở trường / sở đoản
      if (sub.id === 'math' && (index === 0 || index === 4 || index === 35)) base = 9.5;
      if (sub.id === 'eng' && (index === 1 || index === 29)) base = 9.6;
      if (sub.id === 'lit' && (index === 7 || index === 32)) base = 9.0;
      if (sub.id === 'phys' && index === 20) base = 9.2;

      // Sinh điểm ngẫu nhiên chuẩn hóa 0.5
      const clamp = (val: number) => Math.min(10, Math.max(4.0, Math.round(val * 2) / 2));

      const jitter1 = (Math.sin(index * 7 + sub.name.length) * 0.8);
      const jitter2 = (Math.cos(index * 3 + sub.name.length) * 0.7);

      scores[sub.id] = {
        tx1: clamp(base + jitter1),
        tx2: clamp(base - jitter2),
        tx3: clamp(base + 0.3),
        tx4: sub.category === 'core' ? clamp(base - 0.2) : null,
        gk: clamp(base + (jitter1 + jitter2) / 2),
        ck: clamp(base + jitter2),
      };
    });

    result[student.id] = {
      studentId: student.id,
      term: 'HK1',
      scores,
      teacherComment: isTopStudent 
        ? 'Ý thức học tập xuất sắc, tư duy nhạy bén, gương mẫu đi đầu trong phong trào của lớp.'
        : isGoodStudent
        ? 'Chăm chỉ, hoàn thành tốt nhiệm vụ học tập, cần chủ động hơn trong giờ phát biểu.'
        : 'Cần tập trung hơn trong giờ học, tích cực ôn tập các môn khoa học tự nhiên.',
    };
  });

  return result;
}

